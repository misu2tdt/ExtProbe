"""popup_recount.py -- recount, on the development traces, how many extensions declare a popup and how many extension pages the v3 profile opened.

  python evaluation/probe/popup_recount.py --traces <dev traces dir> [--out popup_recount.md] [--exclude canary]

Per trace (<name>/output/events.json): the manifest's default_popup (`action`, `browser_action` or `page_action`) and `extension_pages_opened`. The v3 profile
tries only popup.html, popup/popup.html and options.html (sandbox/base/phases/actions.py, _probe_extension_pages). The traces are not part of this repository
(see evaluation/reproducibility.md). Output: counts only, no extension ids.
"""
import argparse
import json
from pathlib import Path

GUESSED = ("popup.html", "popup/popup.html")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--traces", required=True)
    ap.add_argument("--out", default=str(Path(__file__).with_name("popup_recount.md")))
    ap.add_argument("--exclude", nargs="*", default=["canary"], help="folder names that are not samples (default: canary)")
    a = ap.parse_args(argv)
    n = declared = guessed = no_page = any_page = proxy = 0
    for d in sorted(Path(a.traces).iterdir()):
        p = d / "output" / "events.json"
        if not p.exists() or d.name in a.exclude:
            continue
        try:
            ev = json.loads(p.read_text(encoding="utf-8"))
        except ValueError:
            continue
        n += 1
        m = ev.get("manifest") or {}
        popup = next((v for v in ((m.get(k) or {}).get("default_popup") for k in ("action", "browser_action", "page_action")) if v), None)
        opened = ev.get("extension_pages_opened") or []
        any_page += bool(opened)
        proxy += "proxy" in (m.get("permissions") or [])
        if popup:
            declared += 1
            guessed += popup.lstrip("/") in GUESSED
            no_page += not opened
    L = ["# Popup recount on the development traces", "",
         f"Generated by `evaluation/probe/popup_recount.py` on the {n} development traces (v3 profile; the `canary` smoke folder is excluded). Counts only.", "",
         "| measure | extensions |", "|---|---|",
         f"| traces counted | {n} |",
         f"| declare a popup (`default_popup` in `action`, `browser_action` or `page_action`) | {declared} |",
         f"| of those, the popup is at `popup.html` or `popup/popup.html` (a path v3 tries) | {guessed} |",
         f"| declare a popup and **no extension page was opened at all** | {no_page} |",
         f"| some extension page opened (any of the three paths) | {any_page} |",
         f"| request the `proxy` permission | {proxy} |", "",
         "**Relation to `DESIGN.md`.** `evaluation/probe/DESIGN.md` (copied unchanged from the development repository) reports 290 / 142 / 144 for the first three measures "
         "(and the same 189 and 16). It comes from an earlier count whose script was not preserved; this page is the recount with a script that is in the repository. "
         "The differences are 291 vs 290, 140 vs 142 and 145 vs 144. Use the numbers of this page when citing the script's output."]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[4:13]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
