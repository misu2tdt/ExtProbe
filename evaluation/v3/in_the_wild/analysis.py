"""analysis.py -- aggregate results of the in-the-wild run (sets A and B) of the frozen v3. Aggregates only.

  py -I eval/v3/in_the_wild/analysis.py --samples <dir with A/ and B/> --private <dir outside the repo>

Writes eval/v3/in_the_wild/results.md: counts and rates, no ID, no name, no per-sample score. Per-sample scores / flags go
ONLY to <private>/flags_A.csv and flags_B.csv (outside the repository) until the labels are reconciled
(CRITERIA.md, blind labelling). Flag = score >= 40 (score_v3.py as frozen); Wilson 95 % intervals.
Prediction rules are fixed here, before the numbers are read:
  P1 right iff the Search Hijacking flag rate is below that of the rest of A and the two intervals do not overlap;
     'inconclusive' if lower with overlapping intervals; wrong otherwise.
  P2 right iff more than half of the Policy Violation and Bundling samples have no v3 detector fired.
  P3 right iff the Malware flag rate is above that of the other reasons and below 50 %.
  P4 right iff the 95 % interval of Set B contains 8.9 % or lies above it.
"""
import argparse
import csv
import json
import re
import statistics as st
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO / "eval" / "v3"))
sys.path.insert(0, str(REPO / "eval"))
import test_analysis as TA  # noqa: E402
from expanded_analysis import wilson, pct  # noqa: E402

THR = TA.THRESHOLDS
MAIN = 40


def rate(k, n):
    if n == 0:
        return "n/a"
    lo, hi = wilson(k, n)
    return f"{k} / {n} = {pct(k / n)} ({pct(max(0.0, lo))}-{pct(min(1.0, hi))})"


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]


def reason_group(r):
    r = r or ""
    if "extension_files_missing" in r:
        return "file referenced by the manifest missing"
    if "Insecure CSP value" in r:
        return "MV3 CSP rejects remote / unsafe-eval script-src"
    if "chrome_style" in r:
        return "MV2-only key chrome_style"
    if "content_security_policy" in r:
        return "invalid content_security_policy"
    if "web_accessible_resources" in r:
        return "web_accessible_resources in MV2 form"
    if "load failed" in r:
        return "other load failure"
    if "timeout" in r:
        return "timeout"
    return "other: " + re.sub(r"[^A-Za-z _:]", "", r)[:40] if r else "none given"


def run(man, trace_dir, samples):
    rows = TA.collect([dict(m, category="n/a", name=m["ext_id"], label="x") for m in man], trace_dir, "v3", samples)
    byid = {m["ext_id"]: m for m in man}
    for r in rows:
        m = byid[r["ext_id"]]
        r.update({k: m.get(k, "") for k in ("sentry_reason", "background", "cws_page", "tier")})
        ev = Path(trace_dir) / r["ext_id"] / "output" / "events.json"
        rs = (json.loads(ev.read_text(encoding="utf-8")).get("run_status") or {}) if ev.exists() else {}
        r["reason"] = rs.get("reason")
        r["flag"] = r["run_status"] == "complete" and r["score"] is not None and r["score"] >= MAIN
        r["ok"] = r["run_status"] == "complete" and r["score"] is not None
    return rows


def split(rows, key):
    out = {}
    for r in rows:
        out.setdefault(r[key], []).append(r)
    return out


def frate(rows):
    ok = [r for r in rows if r["ok"]]
    return sum(1 for r in ok if r["flag"]), len(ok)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", required=True)
    ap.add_argument("--private", required=True)
    ap.add_argument("--out", default=str(HERE / "results.md"))
    a = ap.parse_args()
    S = Path(a.samples)
    priv = Path(a.private)
    mA = list(csv.DictReader(open(REPO / "docs" / "samples_manifest_itw_A.csv", encoding="utf-8")))
    tiers = {r["ext_id"]: r["tier"] for r in csv.DictReader(open(HERE / "label_tiers_A.csv", encoding="utf-8"))}
    for m in mA:
        m["tier"] = tiers[m["ext_id"]]
    mB = list(csv.DictReader(open(REPO / "docs" / "samples_manifest_itw_B.csv", encoding="utf-8")))
    A = run(mA, HERE / "traces_A", S / "A")
    B = run(mB, HERE / "traces_B", S / "B")
    for name, rows in (("A", A), ("B", B)):
        with open(priv / f"flags_{name}.csv", "w", encoding="utf-8", newline="") as f:
            w = csv.writer(f)
            w.writerow(["ext_id", "run_status", "score", "flag", "detectors"])
            for r in rows:
                w.writerow([r["ext_id"], r["run_status"], "" if r["score"] is None else int(r["score"]), int(r["flag"]), "+".join(r["fired"])])

    L = ["# In-the-wild run of the frozen v3: aggregate results", "",
         "Generated by `py -I eval/v3/in_the_wild/analysis.py`. Plan and amendments: `CRITERIA.md`. Aggregates only: no ID, no "
         "name, no per-sample score (blind labelling, A1.1). Flag = score >= 40, v3 as frozen, one run per set. **These are flag "
         "rates, not recall or FPR**: Sentry labels are only suspicion and Set B is unlabelled. Wilson 95 % intervals.", ""]

    # runs
    L += ["## 1. Runs", "", "| set | samples | complete | partial | failed | other |", "|---|---|---|---|---|---|"]
    for name, rows in (("A (Sentry-recent)", A), ("B (CWS-random)", B)):
        c = Counter(r["run_status"] for r in rows)
        L.append(f"| {name} | {len(rows)} | {c['complete']} | {c['partial']} | {c['failed']} | {sum(v for k, v in c.items() if k not in ('complete', 'partial', 'failed'))} |")
    for name, rows in (("A", A), ("B", B)):
        bad = [r for r in rows if not r["ok"]]
        if bad:
            L += ["", f"Not complete in {name} (reason from `run_status.reason`; counted as not flagged in the sensitivity row only):", ""]
            L += table(["status", "reason group", "n"], [[s, g, n] for (s, g), n in Counter((r["run_status"], reason_group(r["reason"])) for r in bad).most_common()])
    L.append("")

    # A
    L += ["## 2. Set A (Sentry-recent)", "",
          "| group | flag rate @40 (complete runs) |", "|---|---|"]
    k, n = frate(A)
    L.append(f"| all of A | {rate(k, n)} |")
    L.append(f"| sensitivity: not complete = not flagged (/{len(A)}) | {rate(k, len(A))} |")
    L += ["", "By Sentry reason:", ""]
    L += table(["reason", "samples", "flag rate"], [[g, len(rs), rate(*frate(rs))] for g, rs in sorted(split(A, "sentry_reason").items(), key=lambda x: -len(x[1]))])
    L += ["", "By tier (T2 = vendor report 2026-08-01..10-10, CRITERIA A3.1; the T2 membership rests on the Sentry source field, "
          "ID listing not verified):", ""]
    L += table(["tier", "samples", "flag rate"], [[g, len(rs), rate(*frate(rs))] for g, rs in sorted(split(A, "tier").items())])
    L += ["", "By background in the manifest:", ""]
    L += table(["background", "samples", "flag rate"], [[g, len(rs), rate(*frate(rs))] for g, rs in sorted(split(A, "background").items())])
    L += ["", "By state of the Chrome Web Store page at download:", ""]
    L += table(["cws page", "samples", "flag rate"], [[g, len(rs), rate(*frate(rs))] for g, rs in sorted(split(A, "cws_page").items())])
    L += ["", "By threshold (complete runs):", ""]
    L += table(["threshold", "A", "B"], [[f">= {t}", rate(sum(1 for r in A if r["ok"] and r["score"] >= t), frate(A)[1]),
                                          rate(sum(1 for r in B if r["ok"] and r["score"] >= t), frate(B)[1])] for t in THR])
    L.append("")

    # B
    L += ["## 3. Set B (CWS-random)", "", "| group | samples | flag rate @40 |", "|---|---|---|"]
    k, n = frate(B)
    L.append(f"| all of B | {len(B)} | {rate(k, n)} |")
    for g, rs in sorted(split(B, "background").items()):
        L.append(f"| background = {g} | {len(rs)} | {rate(*frate(rs))} |")
    L.append("")

    # distributions
    L += ["## 4. Score distribution and detectors in the flagged samples (counts by detector, not by sample)", "",
          "| score | A | B |", "|---|---|---|"]
    for lo, hi, lab in TA.BUCKETS:
        L.append(f"| {lab} | " + " | ".join(str(sum(1 for r in rows if r["ok"] and lo <= r["score"] <= hi)) for rows in (A, B)) + " |")
    L.append("| mean / median | " + " | ".join(f"{st.mean(r['score'] for r in rows if r['ok']):.1f} / {st.median(r['score'] for r in rows if r['ok']):g}" for rows in (A, B)) + " |")
    L += ["", "Detector fire counts among **flagged** samples:", ""]
    dets = sorted({d for rows in (A, B) for r in rows if r["flag"] for d in r["fired"]})
    L += table(["detector", "A flagged", "B flagged"], [[d] + [f"{sum(1 for r in rows if r['flag'] and d in r['fired'])} / {sum(1 for r in rows if r['flag'])}" for rows in (A, B)] for d in dets])
    L += ["", "Detector fire counts among **all complete** samples:", ""]
    dets = sorted({d for rows in (A, B) for r in rows if r["ok"] for d in r["fired"]})
    L += table(["detector", "A", "B"], [[d] + [f"{sum(1 for r in rows if r['ok'] and d in r['fired'])} / {frate(rows)[1]}" for rows in (A, B)] for d in dets])
    L.append("")

    # predictions
    L += ["## 5. Registered predictions (CRITERIA section 6) against the numbers", ""]
    sh = [r for r in A if r["sentry_reason"] == "Search Hijacking"]
    rest = [r for r in A if r["sentry_reason"] != "Search Hijacking"]
    k1, n1 = frate(sh)
    k2, n2 = frate(rest)
    lo1, hi1 = wilson(k1, n1) if n1 else (0, 0)
    lo2, hi2 = wilson(k2, n2) if n2 else (0, 0)
    if n1 and n2 and k1 / n1 < k2 / n2:
        p1 = "right" if hi1 < lo2 else "inconclusive (lower, intervals overlap)"
    else:
        p1 = "wrong"
    L.append(f"1. Search Hijacking flagged rarely: {rate(k1, n1)} vs rest of A {rate(k2, n2)} -> **{p1}**.")
    pv = [r for r in A if r["sentry_reason"] in ("Policy Violation", "Bundling Unwanted Software") and r["ok"]]
    nod = sum(1 for r in pv if not r["fired"])
    p2 = "n/a" if not pv else ("right" if nod * 2 > len(pv) else "wrong")
    L.append(f"2. Policy Violation / Bundling may show no runtime behaviour: {nod} of {len(pv)} complete samples have no v3 detector fired "
             f"({'Bundling Unwanted Software has 0 samples in A' if not any(r['sentry_reason'] == 'Bundling Unwanted Software' for r in A) else 'both reasons present'}) -> **{p2}**.")
    mw = [r for r in A if r["sentry_reason"] == "Malware"]
    om = [r for r in A if r["sentry_reason"] != "Malware"]
    k3, n3 = frate(mw)
    k4, n4 = frate(om)
    p3 = "right" if n3 and n4 and k3 / n3 > k4 / n4 and k3 / n3 < 0.5 else "wrong"
    L.append(f"3. Malware flagged more than other reasons but far below 100 %: {rate(k3, n3)} vs other reasons {rate(k4, n4)} -> **{p3}**.")
    kb, nb = frate(B)
    lob, hib = wilson(kb, nb)
    p4 = "right" if hib >= 0.089 else "wrong"
    L.append(f"4. Set B in the range of the benign test (8.9 %) or higher: {rate(kb, nb)} -> **{p4}**.")
    L += ["", "Context: benign held-out test FPR @40 = 8.9 % (17 / 192); MADWeb V3 malware 0 / 415 (`eval/v3/malware_test/results.md`).", ""]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
