"""count_silence.py -- how often the development set's malicious-labeled runs are "silent" for the extension-initiated network detectors.

  python evaluation/v3/dev_silence/count_silence.py --traces <dev traces dir> [--labels <labels_tiers.csv>] [--out results.md]

Population: the runs of the development set whose label (column `label_verified` of evaluation/v3/labels/labels_tiers.csv) is `malicious` and whose
run_status is `complete`. Per run:
  silent       no extension-initiated request at all: score_v3.ext_requests(events) is empty (service-worker requests recorded by the CDP session, plus page
               requests whose outermost caller is extension code: the definition the exfil / undeclared-domain detectors use)
  install tab  an extension-opened tab that score_v3 reports (signal `unsolicited_tab`)
  uninstall    a recorded runtime.setUninstallURL call
  tab_or_unins install tab or uninstall URL;  both = silent AND (install tab or uninstall URL)
The traces are not part of this repository (see evaluation/reproducibility.md). Output: Markdown with counts only, no extension ids.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from extprobe import paths  # noqa: E402
paths.setup()
import score_v3 as S  # noqa: E402


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * (p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5
    return max(0.0, (c - h) / d), min(1.0, (c + h) / d)


def fmt(k, n):
    lo, hi = wilson(k, n)
    return f"{k} / {n} = {100 * k / n:.1f}% ({100 * lo:.1f}%-{100 * hi:.1f}%)"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--traces", required=True, help="dev traces folder: <id>/output/events.json")
    ap.add_argument("--labels", default=str(ROOT / "evaluation/v3/labels/labels_tiers.csv"))
    ap.add_argument("--out", default=str(Path(__file__).with_name("results.md")))
    a = ap.parse_args(argv)
    labels = {r["ext_id"]: r for r in csv.DictReader(open(a.labels, encoding="utf-8", newline=""))}
    rows = []
    for ext_id, r in labels.items():
        if r["label_verified"] != "malicious":
            continue
        p = Path(a.traces) / ext_id / "output" / "events.json"
        if not p.exists():
            continue
        ev = json.loads(p.read_text(encoding="utf-8"))
        if (ev.get("run_status") or {}).get("status") != "complete":
            continue
        silent = len(S.ext_requests(ev)) == 0
        tab = bool(S.detect_tabs(ev))
        unins = any("setUninstallURL" in str(c.get("api", "")) for c in ev.get("api_calls", []) if isinstance(c, dict))
        rows.append((silent, tab, unins))
    n = len(rows)
    c = lambda f: sum(1 for r in rows if f(r))
    silent, tab, unins = c(lambda r: r[0]), c(lambda r: r[1]), c(lambda r: r[2])
    either = c(lambda r: r[1] or r[2])
    both = c(lambda r: r[0] and (r[1] or r[2]))
    L = ["# Development set: how many malicious-labeled runs are silent for the network detectors", "",
         f"Generated by `evaluation/v3/dev_silence/count_silence.py`. Population: {n} runs of the development set labeled malicious by the public datasets "
         "(`label_verified = malicious` in `evaluation/v3/labels/labels_tiers.csv`; see the label terminology in `evaluation/README.md`) whose run completed. "
         "Counts only; Wilson 95% intervals. The traces are not in this repository.", "",
         "Definitions: *extension-initiated request* = an item of `score_v3.ext_requests(events)` (service-worker requests recorded by the CDP session, plus page "
         "requests whose outermost caller is extension code). *Install-time tab* = an extension-opened tab reported by `score_v3` (signal `unsolicited_tab`). "
         "*Uninstall URL* = a recorded `runtime.setUninstallURL` call.", "",
         "| measure | runs |", "|---|---|",
         f"| no extension-initiated request at all | {fmt(silent, n)} |",
         f"| an install-time tab | {fmt(tab, n)} |",
         f"| an uninstall URL | {fmt(unins, n)} |",
         f"| an install-time tab or an uninstall URL | {fmt(either, n)} |",
         f"| **both**: no extension-initiated request **and** (an install-time tab or an uninstall URL) | {fmt(both, n)} |", "",
         "Reading: about half of these runs show no extension-initiated request, and most show an install-time tab or an uninstall URL, which the network detectors do "
         "not look at (an install or uninstall page is common in benign extensions too, see `evaluation/v3/audit/report.md`)."]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[5:]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
