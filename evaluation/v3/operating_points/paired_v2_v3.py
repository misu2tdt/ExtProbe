"""paired_v2_v3.py -- v2 and v3 on the SAME development samples (paired comparison).

  python evaluation/v3/operating_points/paired_v2_v3.py --v2-summary <v2 dev summary.csv> --v3-summary <v3 dev summary_v3.csv> \
         [--v3-traces <dev v3 traces dir>] [--labels evaluation/v3/labels/labels_tiers.csv] [--out paired_v2_v3.md]

Population: the development samples whose label is `malicious` (column `label_verified`, see the label terminology in evaluation/README.md).
v2 set = those with a complete v2 run (283), v3 set = those with a complete v3 run (278); the paired set is their intersection.
Per paired sample: v2 flagged at --v2-threshold (default 81, the v2 threshold matched on the held-out test set; operating_points/results.md section 1c)
and v3 flagged at 40 (pre-registered). McNemar exact test on the discordant pairs; Wilson 95% intervals. Samples are shown by a short sha256 prefix of the id.
The summaries and traces are not part of this repository (see evaluation/reproducibility.md).
"""
import argparse
import csv
import hashlib
import json
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * (p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5
    return max(0.0, (c - h) / d), min(1.0, (c + h) / d)


def cell(k, n):
    lo, hi = wilson(k, n)
    return f"{k} / {n} = {100 * k / n:.1f}% ({100 * lo:.1f}%-{100 * hi:.1f}%)"


def mcnemar_exact(b, c):
    """Two-sided exact p: 2 * P(X <= min(b, c)), X ~ Binomial(b + c, 0.5), capped at 1."""
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(comb(n, i) for i in range(k + 1)) / 2 ** n)


def rd(p):
    return list(csv.DictReader(open(p, encoding="utf-8", newline="")))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--v2-summary", required=True)
    ap.add_argument("--v3-summary", required=True)
    ap.add_argument("--v3-traces", default=None, help="v3 dev traces (<id>/output/events.json): used only to read run_status.reason of unpaired samples")
    ap.add_argument("--labels", default=str(REPO / "evaluation/v3/labels/labels_tiers.csv"))
    ap.add_argument("--v2-threshold", type=int, default=81)
    ap.add_argument("--out", default=str(HERE / "paired_v2_v3.md"))
    a = ap.parse_args(argv)
    mal = [r["ext_id"] for r in rd(a.labels) if r["label_verified"] == "malicious"]
    v2 = {r["ext_id"]: r for r in rd(a.v2_summary)}
    v3 = {r["ext_id"]: r for r in rd(a.v3_summary)}
    ok = lambda src, i: i in src and src[i]["run_status"] == "complete" and src[i]["risk"] != ""
    s2 = [i for i in mal if ok(v2, i)]
    s3 = [i for i in mal if ok(v3, i)]
    both = [i for i in mal if ok(v2, i) and ok(v3, i)]
    only2 = [i for i in s2 if i not in set(s3)]
    only3 = [i for i in s3 if i not in set(s2)]
    short = lambda i: hashlib.sha256(i.encode()).hexdigest()[:8]
    sc = lambda src, i: int(float(src[i]["risk"]))
    T2, T3 = a.v2_threshold, 40
    n = len(both)
    f2 = {i: sc(v2, i) >= T2 for i in both}
    f3 = {i: sc(v3, i) >= T3 for i in both}
    f2_40 = {i: sc(v2, i) >= 40 for i in both}
    both_f = sum(1 for i in both if f2[i] and f3[i])
    only_v2 = sum(1 for i in both if f2[i] and not f3[i])
    only_v3 = sum(1 for i in both if f3[i] and not f2[i])
    none = n - both_f - only_v2 - only_v3
    p = mcnemar_exact(only_v2, only_v3)
    # v2 at the pre-registered 40, for context (same pairs)
    b40 = sum(1 for i in both if f2_40[i] and not f3[i])
    c40 = sum(1 for i in both if f3[i] and not f2_40[i])
    both40 = sum(1 for i in both if f2_40[i] and f3[i])
    none40 = n - both40 - b40 - c40
    reasons = []
    for i in only2 + only3:
        why = ""
        if a.v3_traces:
            ep = Path(a.v3_traces) / i / "output" / "events.json"
            if ep.exists():
                rs = (json.loads(ep.read_text(encoding="utf-8")).get("run_status") or {})
                why = f"{rs.get('status')}: {str(rs.get('reason'))[:110]}"
        reasons.append(f"| `{short(i)}` | {'v2' if i in s2 else 'v3'} only | v2: {v2.get(i, {}).get('run_status')}, v3: {v3.get(i, {}).get('run_status')} | manifest_version {v2.get(i, {}).get('manifest_version') or '?'} (v2 summary) | {why or 'not read (no --v3-traces)'} |")
    L = ["# v2 and v3 on the same development samples (paired)", "",
         "Generated by `evaluation/v3/operating_points/paired_v2_v3.py`. Population: development samples labeled malicious by the public datasets "
         "(`label_verified = malicious`; see the label terminology in `evaluation/README.md`). Counts and Wilson 95% intervals; samples appear only as a short sha256 "
         "prefix of their id. The summaries and traces are not in this repository.", "",
         "## 1. The two populations", "",
         f"| set | samples |", "|---|---|",
         f"| labeled malicious | {len(mal)} |", f"| complete v2 run (the 283 of `results.md`) | {len(s2)} |",
         f"| complete v3 run (the 278 of `results.md`) | {len(s3)} |", f"| both (paired set) | {n} |",
         f"| v2 only | {len(only2)} |", f"| v3 only | {len(only3)} |", "",
         "### Why the sets differ", "",
         "The samples missing from the v3 set have a complete v2 run but a `failed` v3 run (status in the two summaries below); a failed run produces no behavior to score, "
         "so the sample is not counted in the v3 recall. The v3 profile records the load error reported by Chrome (reason column). Whether the same extension actually loaded in the v2 run was not checked here.", "",
         "| sample | in | run status | manifest | v3 `run_status.reason` |", "|---|---|---|---|---|", *reasons, ""]
    L += [f"## 2. Paired comparison on the {n} samples with both runs", "",
          f"v2 flagged at its matched threshold {T2} (chosen on the held-out test set to match v3's false-positive rate, `results.md` section 1c; not a pre-registered operating point) "
          f"and v3 flagged at the pre-registered 40.", "",
          "| | v3 flagged | v3 not flagged |", "|---|---|---|",
          f"| v2 flagged (>= {T2}) | {both_f} (both) | {only_v2} (only v2) |", f"| v2 not flagged | {only_v3} (only v3) | {none} (neither) |", "",
          f"- v2 at {T2}: {cell(sum(f2.values()), n)}", f"- v3 at {T3}: {cell(sum(f3.values()), n)}",
          f"- Discordant pairs: only v2 {only_v2}, only v3 {only_v3}; **McNemar exact test (two-sided) p = {p:.4g}**.", "",
          f"For context, v2 at the pre-registered threshold 40 on the same {n} samples: {cell(sum(f2_40.values()), n)}; "
          f"both {both40}, only v2 {b40}, only v3 {c40}, neither {none40}; McNemar exact p = {mcnemar_exact(b40, c40):.4g}."]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L[7:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
