"""summarize.py -- synthesis of the audit (AUDIT_CRITERIA.md) from audit.csv.

  py eval/v3/audit/summarize.py     # -> eval/v3/audit/summary.md, eval/v3/audit/spotcheck.md

Counts per proposed label and FN group with Wilson 95 % intervals, extrapolation to all FN, the
realistic Tier-2 recall ceiling, and 10 rows drawn with random.Random(7) for a manual check.
"""
import csv
import math
import random
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
POSITIVES = 278          # complete malware with final label malicious (eval/v3/dev/results.md)
TP_ALL = 41
FN_ALL = 237
LABELS = ["malicious-confirmed", "malicious-likely", "grey/PUP", "benign-looking", "inconclusive"]
GROUPS = ["A", "B", "C", "D"]


def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return max(0.0, (c - h) / d), min(1.0, (c + h) / d)


def pct(x):
    return f"{100 * x:.1f}%"


def main():
    rows = list(csv.DictReader(open(HERE / "audit.csv", encoding="utf-8")))
    tp = [r for r in rows if r["kind"] == "TP"]
    fn = [r for r in rows if r["kind"] == "FN"]
    L = ["# Audit synthesis (generated by summarize.py from audit.csv)", "",
         f"Reviewed: {len(tp)} TP (all) + {len(fn)} FN (random, seed 42, out of {FN_ALL}). "
         f"Positives in the dev run: {POSITIVES} (complete, final label malicious).", "",
         "## Proposed labels", "", "| label | TP | FN (95% CI) | FN extrapolated to all FN (95% CI) |", "|---|---|---|---|"]
    tl, fl = Counter(r["proposed_label"] for r in tp), Counter(r["proposed_label"] for r in fn)
    for lab in LABELS:
        lo, hi = wilson(fl[lab], len(fn))
        L.append(f"| {lab} | {tl[lab]} | {fl[lab]} ({pct(lo)}–{pct(hi)}) | ≈ {fl[lab] / len(fn) * FN_ALL:.0f} "
                 f"({lo * FN_ALL:.0f}–{hi * FN_ALL:.0f}) |")
    L += ["", "## FN cause groups", "", "| group | FN | share (95% CI) | extrapolated to all FN (95% CI) |", "|---|---|---|---|"]
    g = Counter(r["fn_group"] for r in fn)
    for k in GROUPS:
        lo, hi = wilson(g[k], len(fn))
        L.append(f"| {k} | {g[k]} | {pct(g[k] / len(fn))} ({pct(lo)}–{pct(hi)}) | ≈ {g[k] / len(fn) * FN_ALL:.0f} "
                 f"({lo * FN_ALL:.0f}–{hi * FN_ALL:.0f}) |")
    c_split = Counter(r["proposed_label"] for r in fn if r["fn_group"] == "C")
    L.append("")
    L.append("Group C by proposed label: " + ", ".join(f"{k} {v}" for k, v in c_split.items()) + ".")
    a_c2 = [r for r in fn if r["fn_group"] == "A" and "C2 check-in observed" in r["note"]]
    L.append(f"Group A with the C2 check-in visible in the trace (payload not triggered): {len(a_c2)}.")

    # ---- recall ceiling ----
    b = g["B"]
    lo, hi = wilson(b, len(fn))
    est_b = b / len(fn) * FN_ALL
    L += ["", "## Realistic Tier-2 recall ceiling", "",
          "Recoverable = group B only (behaviour present in the trace). Labels as used today (all 278 positives).", "",
          "| scenario | recoverable FN (95% CI) | recall ceiling (95% CI) |", "|---|---|---|",
          f"| strict: B | ≈ {est_b:.0f} ({lo * FN_ALL:.0f}–{hi * FN_ALL:.0f}) | {pct((TP_ALL + est_b) / POSITIVES)} "
          f"({pct((TP_ALL + lo * FN_ALL) / POSITIVES)}–{pct((TP_ALL + hi * FN_ALL) / POSITIVES)}) |"]
    b2 = b + len(a_c2)
    lo2, hi2 = wilson(b2, len(fn))
    est_b2 = b2 / len(fn) * FN_ALL
    L.append(f"| lenient: B + A with C2 check-in seen | ≈ {est_b2:.0f} ({lo2 * FN_ALL:.0f}–{hi2 * FN_ALL:.0f}) | "
             f"{pct((TP_ALL + est_b2) / POSITIVES)} ({pct((TP_ALL + lo2 * FN_ALL) / POSITIVES)}–{pct((TP_ALL + hi2 * FN_ALL) / POSITIVES)}) |")
    # audited-label view
    mal = ("malicious-confirmed", "malicious-likely")
    tp_mal = sum(1 for r in tp if r["proposed_label"] in mal)
    fn_mal = sum(1 for r in fn if r["proposed_label"] in mal)
    fn_mal_b = sum(1 for r in fn if r["proposed_label"] in mal and r["fn_group"] == "B")
    est_mal = tp_mal + fn_mal / len(fn) * FN_ALL
    lo3, hi3 = wilson(fn_mal, len(fn))
    L += ["", "With the audited labels instead (only malicious-confirmed / -likely count as positives):", "",
          f"- TP that are malicious by code: {tp_mal} / {len(tp)} ({pct(tp_mal / len(tp))}).",
          f"- FN that are malicious by code: {fn_mal} / {len(fn)} → ≈ {fn_mal / len(fn) * FN_ALL:.0f} of {FN_ALL} "
          f"({lo3 * FN_ALL:.0f}–{hi3 * FN_ALL:.0f}).",
          f"- Estimated code-malicious positives: ≈ {est_mal:.0f}; v3 recall on them ≈ {pct(tp_mal / est_mal)}; "
          f"ceiling with B ≈ {pct((tp_mal + fn_mal_b / len(fn) * FN_ALL) / est_mal)}."]
    (HERE / "summary.md").write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))

    pick = random.Random(7).sample(rows, 10)
    S = ["# Spot check (10 rows, random.Random(7) over the 81 reviewed rows)", "",
         "Check each row by hand against the package and trace; mark agree / disagree.", "",
         "| ext_id | kind | proposed label | FN group | code evidence | trace evidence | agree? |", "|---|---|---|---|---|---|---|"]
    for r in pick:
        S.append(f"| {r['ext_id']} | {r['kind']} | {r['proposed_label']} | {r['fn_group']} | {r['code_evidence'][:160]} | "
                 f"{r['trace_evidence'][:120]} | |")
    (HERE / "spotcheck.md").write_text("\n".join(S) + "\n", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
