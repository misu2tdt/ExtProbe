"""ab_compare.py -- comparison table for the frozen A/B evaluation (FREEZE.md).

Inputs (after the overnight runs):
  A   = eval/ab/A/summary.csv          corpus profile, scored with --scoring auto
  B   = eval/ab/B/summary.csv          v2 profile,     scored with --scoring auto (v2 rules)
  A'  = eval/ab/B/summary_legacy.csv   B's traces,     scored with --scoring legacy (corpus rules)
Optional reference: the paper's eval/results/summary.csv.

For each run the verified labels are added with eval/apply_verified_labels.py (on a copy;
inputs are not modified) and the metrics are computed with eval/save_metrics.py's own
functions (only run_status == complete, as in the paper). Reported:
  - AUC and confusion @40, raw and verified, on each run's own population, and on the
    intersection of samples complete in A, A' and B (the fair paired comparison, since v2
    loads extensions the corpus browser cannot);
  - how often each detector fires;
  - verdict changes @40 between A -> A' (browser + stimuli: same rules, other sandbox) and
    A' -> B (detectors only: same traces, v2 rules), on the intersection.
Writes eval/ab/comparison.md and prints it.

Run: python eval/ab_compare.py [--ab eval/ab]
"""
import argparse
import csv
import shutil
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "eval"))
import apply_verified_labels as avl  # noqa: E402
import save_metrics as sm  # noqa: E402

DETECTORS = ["credential_exfil", "local_harvest", "undeclared_domain_contact", "beaconing",
             "script_injection", "unsolicited_tab"]


def labelled_rows(path: Path):
    """Rows of a summary CSV with verified_label added (apply_verified_labels on a copy)."""
    tmp = Path(tempfile.mkdtemp()) / "summary.csv"
    shutil.copy2(path, tmp)
    old = avl.CSV
    avl.CSV = tmp
    try:
        avl.main()
    finally:
        avl.CSV = old
    rows = list(csv.DictReader(open(tmp, encoding="utf-8")))
    shutil.rmtree(tmp.parent, ignore_errors=True)
    return rows


def metrics(rows):
    vlab = next(c for c in rows[0] if c.lower() == "verified_label")
    out = {}
    for mode in ("raw", "verified"):
        data = sm._build_data(rows, "risk", "label", "run_status", vlab, mode)
        data = data[0] if isinstance(data, tuple) else data
        _, _, table, auc = sm._sweep(data)
        out[mode] = (auc, sm._at(table, 40))
    return out


def fmt(m):
    a, c = m
    return f"{a:.4f} | {c['TP']} / {c['FP']} / {c['FN']} / {c['TN']}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ab", default=str(REPO / "eval" / "ab"))
    a = ap.parse_args()
    ab = Path(a.ab)
    files = {"A (corpus)": ab / "A" / "summary.csv",
             "A' (B traces, corpus rules)": ab / "B" / "summary_legacy.csv",
             "B (v2)": ab / "B" / "summary.csv"}
    missing = [str(p) for p in files.values() if not p.exists()]
    if missing:
        sys.exit("missing: " + ", ".join(missing))
    runs = {k: labelled_rows(p) for k, p in files.items()}
    paper = REPO / "eval" / "results" / "summary.csv"
    if paper.exists():
        runs = {"paper (eval/results)": labelled_rows(paper), **runs}

    complete = {k: {r["ext_id"] for r in rows if r.get("run_status") == "complete"} for k, rows in runs.items()}
    both = set.intersection(*(complete[k] for k in files))

    try:   # repo-relative in the output, so no machine-specific path is written
        ab_shown = ab.resolve().relative_to(REPO).as_posix()
    except ValueError:
        ab_shown = ab.name
    L = ["# A/B comparison", "", f"Generated by `python eval/ab_compare.py --ab {ab_shown}`. "
         "Confusion = TP / FP / FN / TN at threshold 40; only run_status == complete counts.", "",
         "## Each run on its own population", "",
         "| run | samples | complete | AUC raw | confusion raw | AUC verified | confusion verified |",
         "|---|---|---|---|---|---|---|"]
    for k, rows in runs.items():
        m = metrics(rows)
        L.append(f"| {k} | {len(rows)} | {len(complete[k])} | {fmt(m['raw'])} | {fmt(m['verified'])} |")

    L += ["", f"## Paired: the {len(both)} samples complete in A, A' and B", "",
          "| run | AUC raw | confusion raw | AUC verified | confusion verified |", "|---|---|---|---|---|"]
    for k in files:
        m = metrics([r for r in runs[k] if r["ext_id"] in both])
        L.append(f"| {k} | {fmt(m['raw'])} | {fmt(m['verified'])} |")

    L += ["", "## Detector fire counts (complete samples)", "",
          "| detector | " + " | ".join(runs) + " |", "|---|" + "---|" * len(runs)]
    for d in DETECTORS:
        L.append(f"| {d} | " + " | ".join(
            str(sum(1 for r in rows if r.get("run_status") == "complete" and r.get(d) == "1"))
            for rows in runs.values()) + " |")
    by = {k: {r["ext_id"]: r for r in runs[k]} for k in files}
    kA, kA2, kB = list(files)
    diff = sorted(e for e in both if by[kA2][e]["risk"] != by[kB][e]["risk"])
    changes = ", ".join(f"{e} {by[kA2][e]['risk']}→{by[kB][e]['risk']}" for e in diff)
    L += ["", "affiliate_hijack is not a summary.csv column. The v2-only rules (beaconing on "
          "extension-initiated requests, affiliate_hijack) change the risk of "
          f"{len(diff)} paired sample(s) between A′ and B" + (f": {changes}" if diff else "") + "."]

    def flips(k0, k1):
        up = sorted(e for e in both if float(by[k0][e]["risk"]) < 40 <= float(by[k1][e]["risk"]))
        down = sorted(e for e in both if float(by[k1][e]["risk"]) < 40 <= float(by[k0][e]["risk"]))
        return up, down

    L += ["", "## Verdict changes at 40 (paired samples)", "",
          "| step | what changes | newly ≥ 40 | no longer ≥ 40 |", "|---|---|---|---|"]
    for k0, k1, what in ((kA, kA2, "browser + stimuli (same rules)"), (kA2, kB, "detectors only (same traces)")):
        up, down = flips(k0, k1)
        lab = lambda e: f"{e} ({by[k1][e].get('verified_label') or by[k1][e].get('label')})"
        L.append(f"| {k0} → {k1} | {what} | {len(up)}: {', '.join(map(lab, up)) or '—'} | "
                 f"{len(down)}: {', '.join(map(lab, down)) or '—'} |")
    out = ab / "comparison.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    print(f"\n-> {out}")


if __name__ == "__main__":
    main()
