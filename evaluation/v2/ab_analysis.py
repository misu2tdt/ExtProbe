"""ab_analysis.py -- read-only analysis of the frozen A/B run (FREEZE.md) -> eval/ab/analysis.md.

Uses the run's own outputs only (no sandbox, no detector change):
  paper eval/results, A eval/ab/A, A' = eval/ab/B scored with risk.legacy_view, B eval/ab/B.
Summary rows come from the summary CSVs (verified labels added by eval/apply_verified_labels.py
on copies); per-sample details (which detector, which host) are recomputed from the traces
with worker/risk.py -- the same code that produced the CSVs.

Run: python eval/ab_analysis.py
"""
import collections
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "worker"))
sys.path.insert(0, str(REPO / "eval"))
sys.path.insert(0, str(REPO))
import risk  # noqa: E402
from ab_compare import labelled_rows, metrics  # noqa: E402
from extprobe.report import host_label, own_domains  # noqa: E402

AB = REPO / "eval" / "ab"
DIRS = {"paper": REPO / "eval" / "results", "A": AB / "A", "A'": AB / "B", "B": AB / "B"}
CSVS = {"paper": DIRS["paper"] / "summary.csv", "A": AB / "A" / "summary.csv",
        "A'": AB / "B" / "summary_legacy.csv", "B": AB / "B" / "summary.csv"}
DET6 = ["credential_exfil", "local_harvest", "undeclared_domain_contact", "beaconing",
        "script_injection", "unsolicited_tab"]
DET7 = DET6 + ["affiliate_hijack"]
NEG = ("benign", "benign_mislabel")      # negatives in the verified metrics (save_metrics)

_cache = {}


def report(run, eid):
    """(events, report, risk, level, breakdown) recomputed from the trace, or None."""
    key = (run, eid)
    if key not in _cache:
        p = DIRS[run] / eid / "output" / "events.json"
        if not p.exists():
            _cache[key] = None
        else:
            ev = json.loads(p.read_text(encoding="utf-8"))
            if run == "A'":
                ev = risk.legacy_view(ev)
            rep = risk.build_behavioral_report(ev)
            r, lvl, bd = risk.compute_risk_score(rep)
            _cache[key] = (ev, rep, r, lvl, bd)
    return _cache[key]


def fired(run, eid):
    x = report(run, eid)
    return {d for d in DET7 if x and x[1]["indicators"].get(d)}


def pct(a, b):
    return f"{a / b:.3f}" if b else "—"


def detector_hosts(run, eid):
    """{detector: [hosts]} for the detectors that fired."""
    ev, rep, *_ = report(run, eid)
    dyn, out = rep["dynamic"], {}
    if rep["indicators"]["undeclared_domain_contact"]:
        out["undeclared_domain_contact"] = dyn["undeclared_domains"]["undeclared_total"]
    if rep["indicators"]["beaconing"]:
        out["beaconing"] = [b["host"] for b in dyn["beaconing"]["beacons"]]
    if rep["indicators"]["script_injection"]:
        out["script_injection"] = sorted({n["host"] for n in dyn["script_injection"]["injected_nodes"]})
    if rep["indicators"]["unsolicited_tab"]:
        from urllib.parse import urlparse
        out["unsolicited_tab"] = sorted({urlparse(t["url"]).hostname or t["url"][:40]
                                         for t in dyn["unsolicited_tabs"]["unsolicited_tabs"]})
    if rep["indicators"].get("affiliate_hijack"):
        from urllib.parse import urlparse
        out["affiliate_hijack"] = sorted({urlparse(h["url"]).hostname for h in dyn["affiliate_hijack"]["hits"]})
    if rep["indicators"]["credential_exfil"]:
        out["credential_exfil"] = ["(honeypot marker in request)"]
    if rep["indicators"]["local_harvest"]:
        out["local_harvest"] = ["(marker in storage)"]
    return out


def labelled_hosts(run, eid, hosts):
    own = own_domains((report(run, eid)[0].get("manifest") or {}))
    res = []
    for h in hosts:
        lab = host_label(h, own)
        res.append(f"{h} [{lab[0]}]" if lab else h)
    return res


def main():
    rows = {k: {r["ext_id"]: r for r in labelled_rows(p)} for k, p in CSVS.items()}
    vlab = {e: (r.get("verified_label") or r.get("label")) for e, r in rows["A"].items()}
    complete = {k: {e for e, r in rs.items() if r.get("run_status") == "complete"} for k, rs in rows.items()}
    paired = complete["A"] & complete["A'"] & complete["B"]
    L = ["# A/B analysis", "",
         "Generated by `python eval/ab_analysis.py` (read-only: no sandbox run, no detector change) "
         "from the frozen A/B run (FREEZE.md, tag v2.0-freeze). A = corpus profile; B = v2; "
         "A′ = B's traces scored with the corpus rules (`rescore --scoring legacy`). Verified "
         "labels: malicious = positive; benign and benign_mislabel = negative; grey and "
         "unknown_verify excluded (as in the paper). Threshold 40.", ""]

    # ---- 2. paired main table
    L += ["## 1. Main table — paired samples", "",
          f"Samples per run: 354. Complete: paper {len(complete['paper'])}, A {len(complete['A'])}, "
          f"A′ {len(complete[chr(65) + chr(39)])}, B {len(complete['B'])}. "
          f"**Paired (complete in A, A′ and B): N = {len(paired)}.**", "",
          "| run | labels | N used | AUC | TP | FP | FN | TN | precision | recall | FPR |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for k in ("A", "A'", "B"):
        m = metrics([r for e, r in rows[k].items() if e in paired])
        for mode in ("raw", "verified"):
            auc, c = m[mode]
            tp, fp, fn, tn = c["TP"], c["FP"], c["FN"], c["TN"]
            L.append(f"| {k} | {mode} | {tp + fp + fn + tn} | {auc:.4f} | {tp} | {fp} | {fn} | {tn} | "
                     f"{pct(tp, tp + fp)} | {pct(tp, tp + fn)} | {pct(fp, fp + tn)} |")

    # ---- 3. paper vs A
    both = complete["paper"] & complete["A"]
    mal = [e for e in both if vlab.get(e) == "malicious"]
    dec = [e for e in mal if float(rows["A"][e]["dynamic_score"]) < float(rows["paper"][e]["dynamic_score"])]
    inc = [e for e in mal if float(rows["A"][e]["dynamic_score"]) > float(rows["paper"][e]["dynamic_score"])]
    lost = collections.Counter(d for e in mal for d in DET6
                               if rows["paper"][e][d] == "1" and rows["A"][e][d] == "0")
    gain = collections.Counter(d for e in mal for d in DET6
                               if rows["paper"][e][d] == "0" and rows["A"][e][d] == "1")
    pm, am = metrics([rows["paper"][e] for e in both]), metrics([rows["A"][e] for e in both])
    flips = [(e, rows["paper"][e]["risk"], rows["A"][e]["risk"]) for e in both
             if (float(rows["paper"][e]["risk"]) >= 40) != (float(rows["A"][e]["risk"]) >= 40)]
    L += ["", "## 2. A vs the paper (same corpus profile, run ~2 months later)", "",
          f"Both complete: {len(both)}. Verified AUC paper {pm['verified'][0]:.4f} → A {am['verified'][0]:.4f}; "
          f"@40 paper {'/'.join(str(pm['verified'][1][x]) for x in ('TP', 'FP', 'FN', 'TN'))} → A "
          f"{'/'.join(str(am['verified'][1][x]) for x in ('TP', 'FP', 'FN', 'TN'))} (TP/FP/FN/TN).", "",
          f"Verified-malicious samples complete in both: {len(mal)}. Dynamic score lower in A: "
          f"**{len(dec)}**; higher: {len(inc)}; equal: {len(mal) - len(dec) - len(inc)}.", "",
          "| detector | malicious samples that lost it (paper → A) | gained it |", "|---|---|---|"]
    for d in DET6:
        L.append(f"| {d} | {lost.get(d, 0)} | {gain.get(d, 0)} |")
    L += ["", "Verdict changes at 40, paper → A: " + (", ".join(
        f"{e} ({vlab.get(e)}) {p}→{a}" for e, p, a in sorted(flips)) or "none") + "."]

    # ---- 4. A -> A'
    def verdict_changes(k0, k1):
        out = []
        for e in sorted(paired):
            r0, r1 = float(rows[k0][e]["risk"]), float(rows[k1][e]["risk"])
            if (r0 >= 40) != (r1 >= 40):
                f0, f1 = fired(k0, e), fired(k1, e)
                out.append((e, vlab.get(e), int(r0), int(r1), sorted(f1 - f0), sorted(f0 - f1),
                            rows[k0][e]["dynamic_score"], rows[k1][e]["dynamic_score"]))
        return out

    L += ["", "## 3. A → A′ (new browser + v2 stimuli; same corpus rules)", "",
          "| sample | label | risk A → A′ | dynamic A → A′ | detectors added | detectors lost |",
          "|---|---|---|---|---|---|"]
    for e, lab, r0, r1, add, rem, d0, d1 in verdict_changes("A", "A'"):
        L.append(f"| {e} | {lab} | {r0} → {r1} | {d0} → {d1} | {', '.join(add) or '—'} | {', '.join(rem) or '—'} |")
    beac = collections.Counter()
    for e in complete["A'"]:
        x = report("A'", e)
        if x and x[1]["indicators"]["beaconing"]:
            for b in x[1]["dynamic"]["beaconing"]["beacons"]:
                beac[b["host"]] += 1
    n_beac = sum(1 for e in complete["A'"] if "beaconing" in fired("A'", e))
    L += ["", f"Beaconing under the corpus rules fires on {n_beac} v2 traces (A′) vs "
          f"{sum(1 for e in complete['A'] if rows['A'][e]['beaconing'] == '1')} in A. Most frequent beacon "
          "hosts in A′: " + ", ".join(f"{h} ({n})" for h, n in
                                     sorted(beac.items(), key=lambda x: (-x[1], x[0]))[:12]) + "."]
    # Harness artefact: under the corpus rules beaconing counts page-initiated requests, and the
    # v2 product probe itself loads /shop-test, two product links and a reload at the target
    # hosts (>= 4 regular document requests). Quantify it; the sensitivity score drops only
    # beacons on the trace's own target_matched hosts (analysis only, not a scoring rule).
    def targets(e):
        ev = report("A'", e)[0]
        return set(ev.get("target_matched_visited") or ev.get("target_matched_hosts") or [])

    def on_target(h, ts):
        return any(h == t or h.endswith("." + t) for t in ts)

    def adj_risk(e):
        ev, rep, r, *_ = report("A'", e)
        b = rep["dynamic"]["beaconing"]
        keep = [x for x in b["beacons"] if not on_target(x["host"], targets(e))]
        if len(keep) == len(b["beacons"]):
            return r
        rep2 = json.loads(json.dumps(rep))
        rep2["dynamic"]["beaconing"] = dict(b, beacons=keep, has_beaconing=bool(keep),
                                            has_undeclared_beacon=any(x["host_undeclared"] for x in keep))
        rep2["indicators"]["beaconing"] = bool(keep)
        return risk.compute_risk_score(rep2)[0]

    harness_only = [e for e in complete["A'"] if "beaconing" in fired("A'", e)
                    and all(on_target(b["host"], targets(e)) for b in report("A'", e)[1]["dynamic"]["beaconing"]["beacons"])]
    adj = {e: dict(rows["A'"][e], risk=str(adj_risk(e))) for e in paired}
    am2 = metrics(list(adj.values()))
    flip_h = [x for x in verdict_changes("A", "A'") if "beaconing" in x[4]
              and (float(adj[x[0]]["risk"]) >= 40) == (float(rows["A"][x[0]]["risk"]) >= 40)]
    L += ["", f"**Harness artefact.** On {len(harness_only)} of these {n_beac} traces every beacon host is a "
          "target_matched host the sandbox itself drives (the v2 product probe: /shop-test, two product "
          "links, a reload; for all-hosts extensions amazon.com and aliexpress.com). The corpus rules count "
          "those page-initiated requests; the v2 rule (B) does not. A′ therefore over-counts beaconing, and "
          "A → A′ is not a clean browser comparison for this detector. Sensitivity (analysis only): A′ "
          "without beacons on its own target hosts —", "",
          "| run | labels | AUC | TP | FP | FN | TN |", "|---|---|---|---|---|---|---|"]
    for mode in ("raw", "verified"):
        auc, c = am2[mode]
        L.append(f"| A′ minus harness beacons | {mode} | {auc:.4f} | {c['TP']} | {c['FP']} | {c['FN']} | {c['TN']} |")
    L += ["", "A → A′ verdict changes that depend on such harness beacons (they revert without them): "
          + (", ".join(f"{x[0]} ({x[1]}) {x[2]}→{x[3]}" for x in flip_h) or "none") + "."]

    incompat = []
    for e, r in rows["A"].items():
        ev = DIRS["A"] / e / "output" / "events.json"
        reason = ""
        if ev.exists():
            reason = (json.loads(ev.read_text(encoding="utf-8")).get("run_status") or {}).get("reason") or ""
        if r.get("run_status") != "complete":
            incompat.append((e, r.get("run_status"), reason))
    L += ["", "Samples not complete in A and their result in B:", "",
          "| sample | label | A status | A reason | B status | B risk | B detectors |", "|---|---|---|---|---|---|---|"]
    for e, st, reason in sorted(incompat, key=lambda x: ("incompatible" not in x[2], x[0])):
        b = rows["B"].get(e, {})
        L.append(f"| {e} | {vlab.get(e)} | {st} | {reason[:70]} | {b.get('run_status')} | "
                 f"{b.get('risk', '')} {b.get('level', '')} | {', '.join(sorted(fired('B', e))) or '—'} |")

    # ---- 5. A' -> B
    L += ["", "## 4. A′ → B (detectors only; same traces)", "",
          "| sample | label | risk A′ → B | cause |", "|---|---|---|---|"]
    for e, lab, r0, r1, add, rem, *_ in verdict_changes("A'", "B"):
        cause = []
        if "affiliate_hijack" in add:
            cause.append("affiliate_hijack fires (v2 only)")
        if "beaconing" in rem:
            cause.append("beaconing dropped: page-initiated requests (v2 provenance rule)")
        L.append(f"| {e} | {lab} | {r0} → {r1} | {'; '.join(cause) or ', '.join(add + rem)} |")
    changed = [e for e in paired if rows["A'"][e]["risk"] != rows["B"][e]["risk"]]
    by_aff = [e for e in changed if "affiliate_hijack" in fired("B", e)]
    by_beac = [e for e in changed if "beaconing" in fired("A'", e) and "beaconing" not in fired("B", e)]
    aff_fire = [e for e in complete["B"] if "affiliate_hijack" in fired("B", e)]
    aff_by = collections.Counter(vlab.get(e) for e in aff_fire)
    L += ["", f"Risk changed A′ → B on {len(changed)} paired samples: beaconing dropped by the "
          f"provenance rule on {len(by_beac)}, affiliate_hijack on {len(by_aff)}"
          + (f" (both: {len(set(by_aff) & set(by_beac))})" if set(by_aff) & set(by_beac) else "") + ".", "",
          f"affiliate_hijack fires on {len(aff_fire)} B traces: "
          + ", ".join(f"{k} {v}" for k, v in sorted(aff_by.items())) + ". Samples: "
          + ", ".join(f"{e} ({vlab.get(e)}, {rows['B'][e]['risk']})" for e in sorted(aff_fire)) + "."]
    neg_aff = [e for e in aff_fire if vlab.get(e) not in ("malicious",)]
    L.append(f"Non-malicious samples with affiliate_hijack: {', '.join(neg_aff) if neg_aff else 'none'}.")

    # ---- 6. FP in B
    fps = sorted(e for e in complete["B"] if vlab.get(e) in NEG and float(rows["B"][e]["risk"]) >= 40)
    greys = sorted(e for e in complete["B"] if vlab.get(e) == "grey" and float(rows["B"][e]["risk"]) >= 40)
    L += ["", "## 5. False positives in B (verified benign / benign_mislabel, risk ≥ 40)", "",
          f"{len(fps)} samples ({sum(1 for e in fps if e in paired)} of them in the paired set). Host tags: "
          "[extension's own domain] = named in the manifest; [analytics]/[CDN] = report label list "
          "(display only, not used in scoring).", "",
          "| sample | label | risk | static / dynamic | detector → hosts |", "|---|---|---|---|---|"]
    for e in fps:
        b = rows["B"][e]
        det = "; ".join(f"{d}: {', '.join(labelled_hosts('B', e, hs)[:6])}" for d, hs in detector_hosts("B", e).items())
        L.append(f"| {e} | {vlab.get(e)} | {b['risk']} {b['level']} | {b['static_score']} / {b['dynamic_score']} | {det} |")
    L += ["", "Grey (excluded from the verified metrics) with risk ≥ 40 in B: "
          + (", ".join(f"{e} {rows['B'][e]['risk']}" for e in greys) or "none") + "."]

    # ---- 7. FN in B
    mal_all = [e for e, r in rows["B"].items() if vlab.get(e) == "malicious"]
    fns = sorted(e for e in mal_all if e in complete["B"] and float(rows["B"][e]["risk"]) < 40)
    cat = collections.defaultdict(list)
    for e in fns:
        d = float(rows["B"][e]["dynamic_score"])
        cat["no dynamic signal (dynamic 0)" if d == 0 else "weak signal (dynamic > 0, risk < 40)"].append(e)
    runerr = sorted(e for e in mal_all if e not in complete["B"])
    L += ["", "## 6. False negatives in B (verified malicious, risk < 40)", "",
          f"{len(fns)} complete samples below 40, plus {len(runerr)} malicious samples whose run did not "
          "complete (not counted in the metrics).", "",
          "| category | n | samples |", "|---|---|---|"]
    for k in ("no dynamic signal (dynamic 0)", "weak signal (dynamic > 0, risk < 40)"):
        L.append(f"| {k} | {len(cat[k])} | {', '.join(cat[k])} |")
    L.append(f"| run did not complete | {len(runerr)} | "
             + ", ".join(f"{e} ({rows['B'][e].get('run_status')})" for e in runerr) + " |")
    weak = collections.Counter(d for e in cat["weak signal (dynamic > 0, risk < 40)"] for d in fired("B", e))
    L += ["", "Detectors among the weak-signal FNs: " + ", ".join(f"{d} {n}" for d, n in weak.most_common()) + "."]

    out = AB / "analysis.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(L))
    print(f"\n-> {out}")


if __name__ == "__main__":
    main()
