"""affiliate_weight.py -- sensitivity of scores to the affiliate_hijack weight (30 vs 40).

Inputs: the v2 traces of eval/measure_affiliate_detector.py (gitignored; regenerate with
`python eval/measure_affiliate_detector.py` and `... --only honey rakuten capitaloneshopping
--target-host amazon.com`):
  eval/affiliate_detector/<id>/output/events.json            5 SP3b link rewriters + 10 benign
  eval/affiliate_detector/host_amazon.com/<id>/output/events.json   3 coupon extensions at amazon.com
Each trace is scored with worker/risk.py twice, with DYNAMIC_WEIGHTS["affiliate_hijack"] set
to 30 and to 40 (everything else unchanged). Corpus traces are not affected at all:
affiliate_hijack is off for non-v2 traces.

Run: python eval/sensitivity/affiliate_weight.py   (writes affiliate_weight.md here)
"""
import csv
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "worker"))
import risk  # noqa: E402

BASE = REPO / "eval" / "affiliate_detector"
OUT_MD = Path(__file__).resolve().parent / "affiliate_weight.md"
WEIGHTS = (30, 40)


def score(events, w):
    old = risk.DYNAMIC_WEIGHTS["affiliate_hijack"]
    risk.DYNAMIC_WEIGHTS["affiliate_hijack"] = w
    try:
        rep = risk.build_behavioral_report(events)
        r, lvl, _ = risk.compute_risk_score(rep)
        return rep["indicators"]["affiliate_hijack"], r, lvl
    finally:
        risk.DYNAMIC_WEIGHTS["affiliate_hijack"] = old


def main():
    paper = {r["ext_id"]: r for r in csv.DictReader(open(REPO / "eval/results/summary.csv", encoding="utf-8"))}
    traces = [(p.parts[-3], "test page at manifest target / shop.bench.test", p)
              for p in sorted(BASE.glob("*/output/events.json")) if not p.parts[-3].startswith("host_")]
    traces += [(p.parts[-3], "test page at amazon.com", p)
               for p in sorted(BASE.glob("host_amazon.com/*/output/events.json"))]
    if not traces:
        sys.exit(f"no traces under {BASE}; run eval/measure_affiliate_detector.py first")

    rows = []
    for eid, setup, p in traces:
        ev = json.loads(p.read_text(encoding="utf-8"))
        res = {w: score(ev, w) for w in WEIGHTS}
        lab = paper.get(eid, {})
        rows.append((eid, lab.get("verified_label") or lab.get("label") or "?", lab.get("risk", ""), setup, res))

    L = ["# Sensitivity: affiliate_hijack weight 30 vs 40", "",
         "Generated by `python eval/sensitivity/affiliate_weight.py` from the v2 traces of",
         "`eval/measure_affiliate_detector.py` (product test page served in target_matched).",
         "Only the affiliate_hijack weight differs between the two columns. Decision: **40**",
         "(author, 2026-10-02; reasons in `worker/risk.py` at `AFFILIATE_HIJACK_WEIGHT`).",
         "Corpus (paper) scores are unaffected: the detector is off for non-v2 traces.", "",
         "| ext_id | label (verified) | paper risk (corpus) | setup | fires | risk @30 | risk @40 | ≥40 @30 → @40 |",
         "|---|---|---|---|---|---|---|---|"]
    for eid, lab, prisk, setup, res in rows:
        f30, r30, l30 = res[30]
        _, r40, l40 = res[40]
        L.append(f"| {eid} | {lab} | {prisk} | {setup} | {'yes' if f30 else 'no'} | {r30} {l30} | "
                 f"{r40} {l40} | {'yes' if r30 >= 40 else 'no'} → {'yes' if r40 >= 40 else 'no'} |")
    fired = [r for r in rows if r[4][30][0]]
    crossed = [r[0] for r in fired if r[4][30][1] < 40 <= r[4][40][1]]
    benign_fired = [r[0] for r in fired if r[1] != "malicious"]
    L += ["",
          f"- affiliate_hijack fires on {len(fired)} of {len(rows)} traces; on benign / grey samples: "
          f"{len(benign_fired)}" + (f" ({', '.join(benign_fired)})" if benign_fired else "") + ".",
          f"- Raising the weight from 30 to 40 moves {len(crossed)} trace(s) across the flag threshold 40"
          + (f": {', '.join(crossed)}" if crossed else "") + ".",
          "- Traces where it does not fire score the same at both weights.", ""]
    OUT_MD.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
