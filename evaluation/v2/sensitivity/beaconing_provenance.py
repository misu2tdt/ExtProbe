"""beaconing_provenance.py -- sensitivity of the paper's corpus numbers to counting only
extension-initiated requests in detect_beaconing (the rule worker/risk.py applies to v2
traces only).

For every corpus trace (eval/results/*/output/events.json) it scores the report twice with
worker/risk.py: as is (legacy: page + SW requests), and with beaconing recomputed on the
requests the extension started -- origin "service_worker" or request_provenance[host] True,
the same rule as detect_undeclared_domains. Only beaconing is recomputed; every other signal
is unchanged. Metrics (AUC, confusion @40, raw and verified) are computed with
eval/save_metrics.py's own functions on summary.csv with the changed risks substituted.
Nothing in eval/results is written.

Run: python eval/sensitivity/beaconing_provenance.py   (writes beaconing_provenance.md here)
"""
import copy
import csv
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "worker"))
sys.path.insert(0, str(REPO / "eval"))
import risk  # noqa: E402
import save_metrics as sm  # noqa: E402

RESULTS = REPO / "eval" / "results"
OUT_MD = Path(__file__).resolve().parent / "beaconing_provenance.md"


def ext_initiated(r, prov):
    host = r.get("host") or risk._host_of(r.get("url", ""))
    return r.get("origin") == "service_worker" or bool(prov.get(host))


def rescore(events):
    rep = risk.build_behavioral_report(events)
    before = risk.compute_risk_score(rep)[0]
    prov = events.get("request_provenance") or {}
    ev2 = dict(events, network_requests=[r for r in events.get("network_requests", [])
                                         if ext_initiated(r, prov)])
    rep2 = copy.deepcopy(rep)
    rep2["dynamic"]["beaconing"] = b2 = risk.detect_beaconing(ev2)
    rep2["indicators"]["beaconing"] = b2["has_beaconing"]
    return rep, before, risk.compute_risk_score(rep2)[0]


def metrics(rows):
    cols = list(rows[0].keys())
    vlab = next(c for c in cols if c.lower() == "verified_label")
    out = {}
    for mode in ("raw", "verified"):
        data = sm._build_data(rows, "risk", "label", "run_status", vlab, mode)
        data = data[0] if isinstance(data, tuple) else data
        _, _, table, auc = sm._sweep(data)
        out[mode] = (auc, sm._at(table, 40))
    return out


def main():
    rows = list(csv.DictReader(open(RESULTS / "summary.csv", encoding="utf-8")))
    by_id = {r["ext_id"]: r for r in rows}
    fired, changed = 0, []
    for p in sorted(RESULTS.glob("*/output/events.json")):
        eid = p.parts[-3]
        rep, before, after = rescore(json.loads(p.read_text(encoding="utf-8")))
        fired += bool(rep["indicators"]["beaconing"])
        if after != before:
            hosts = ", ".join(b["host"] for b in rep["dynamic"]["beaconing"]["beacons"])
            changed.append((eid, by_id.get(eid, {}), before, after, hosts))
    new = {eid: a for eid, _, _, a, _ in changed}
    m0 = metrics(rows)
    m1 = metrics([dict(r, risk=str(new.get(r["ext_id"], r["risk"]))) for r in rows])

    L = ["# Sensitivity: beaconing counted on extension-initiated requests only", "",
         "Generated by `python eval/sensitivity/beaconing_provenance.py` from the 354 corpus traces",
         "(`eval/results/*/output/events.json`) and `eval/results/summary.csv`; nothing in",
         "`eval/results` is changed.", "",
         "**Question.** `detect_beaconing` (legacy, used for the paper) groups every request with a",
         "timestamp, whoever started it. `detect_undeclared_domains` counts only requests the",
         "extension started (service worker, or a host with `request_provenance` True). What do",
         "the paper's numbers become if beaconing used the same provenance rule? Since",
         "2026-10-02 `worker/risk.py` applies that rule to **v2 traces only**; corpus traces keep",
         "the legacy behaviour, so the published numbers are unchanged.", "",
         f"**Corpus.** Beaconing fires on {fired} traces; on {len(changed)} of them every beacon host is",
         "reached only by page-initiated requests (e.g. a video player on a welcome page the",
         "extension opened), so the rule removes the signal there.", "",
         "| ext_id | label (raw / verified) | risk legacy | risk ext-only | beacon host(s) |",
         "|---|---|---|---|---|"]
    for eid, r, b, a, hosts in changed:
        L.append(f"| {eid} | {r.get('label', '?')} / {r.get('verified_label', '?')} | {b} | {a} | {hosts} |")
    L += ["", "| metric | legacy (paper) | extension-initiated only |", "|---|---|---|"]
    for mode in ("verified", "raw"):
        (a0, c0), (a1, c1) = m0[mode], m1[mode]
        L.append(f"| AUC ({mode}) | {a0:.4f} | {a1:.4f} |")
        f = lambda c: f"TP {c['TP']} / FP {c['FP']} / FN {c['FN']} / TN {c['TN']}"
        L.append(f"| confusion @40 ({mode}) | {f(c0)} | {f(c1)} |")
    crossed = [eid for eid, _, b, a, _ in changed if (b >= 40) != (a >= 40)]
    L += ["", f"Scores crossing the threshold 40: {len(crossed)}"
          + (f" ({', '.join(crossed)})" if crossed else "") + ".", "",
          "**For Threats to validity.** The legacy rule attributes to an extension the periodic",
          "traffic of pages it merely opens. On this corpus the effect is small: "
          f"{len(changed)} risk scores drop by "
          f"{min(b - a for _, _, b, a, _ in changed)}–{max(b - a for _, _, b, a, _ in changed)} points, none "
          "crosses the decision threshold, the confusion matrix at 40 is unchanged and AUC moves "
          f"by {abs(m0['verified'][0] - m1['verified'][0]):.4f} (verified) / "
          f"{abs(m0['raw'][0] - m1['raw'][0]):.4f} (raw).", ""]
    OUT_MD.write_text("\n".join(L), encoding="utf-8", newline="\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
