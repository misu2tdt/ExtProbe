"""run.py -- detector unit tests on synthetic events.json (Tier 2).

Each tests/detectors/cases/<case_id>.json holds:
  {"description": "...",
   "events": {...minimal events.json...},
   "expect": {"fire": [...], "not_fire": [...], "risk": int|null, "level": str|null,
              "breakdown": {...optional subset of compute_risk_score's breakdown...}}}

The case is scored with worker/risk.py exactly as the worker does
(build_behavioral_report -> compute_risk_score); risk.py is not modified.
A detector "fires" when report["indicators"][name] is truthy.

Run:    python tests/detectors/run.py      (exit 1 if any case FAILs)
pytest: pytest tests/detectors/run.py
Matrix: python tests/detectors/run.py --matrix [--canary F] [--provenance F] -> matrix.md
        (defaults: fixtures/canary_corpus.json, fixtures/provenance_corpus.json)
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
sys.path.insert(0, str(REPO / "worker"))
from risk import build_behavioral_report, compute_risk_score, legacy_view  # noqa: E402

CASES_DIR = HERE / "cases"
MATRIX_MD = HERE / "matrix.md"
FIXTURES = HERE / "fixtures"
CANARY_EVENTS = FIXTURES / "canary_corpus.json"
PROVENANCE_EVENTS = FIXTURES / "provenance_corpus.json"
DETECTORS = ["credential_exfil", "local_harvest", "undeclared_domain_contact",
             "beaconing", "script_injection", "unsolicited_tab", "affiliate_hijack"]


def run_case(path: Path) -> dict:
    case = json.loads(path.read_text(encoding="utf-8"))
    exp = case["expect"]
    events = case["events"]
    if case.get("scoring") == "legacy":      # score with the corpus rules (eval/rescore.py --scoring legacy)
        events = legacy_view(events)
    report = build_behavioral_report(events)
    risk, level, breakdown = compute_risk_score(report)
    fired = {d for d in DETECTORS if report["indicators"].get(d)}

    problems = []
    for d in exp.get("fire", []):
        if d not in fired:
            problems.append(f"{d} expected to fire")
    for d in exp.get("not_fire", []):
        if d in fired:
            problems.append(f"{d} must not fire")
    if exp.get("risk") is not None and risk != exp["risk"]:
        problems.append(f"risk {risk} != {exp['risk']}")
    if exp.get("level") is not None and level != exp["level"]:
        problems.append(f"level {level} != {exp['level']}")
    for k, v in (exp.get("breakdown") or {}).items():
        if breakdown.get(k) != v:
            problems.append(f"{k} {breakdown.get(k)} != {v}")
    return {"case": path.stem, "fired": sorted(fired), "risk": risk, "level": level,
            "breakdown": breakdown, "problems": problems}


def run_all() -> list:
    return [run_case(p) for p in sorted(CASES_DIR.glob("*.json"))]


def print_table(results: list) -> None:
    w = max([len(r["case"]) for r in results] + [4])
    print(f"{'case':<{w}}  {'fired':<36} {'s':>3} {'s_eff':>5} {'d':>3} {'risk':>4}  {'level':<8} result")
    for r in results:
        b = r["breakdown"]
        print(f"{r['case']:<{w}}  {','.join(r['fired']) or '-':<36} {b['static_score']:>3} "
              f"{b['static_effective']:>5} {b['dynamic_score']:>3} {r['risk']:>4}  {r['level']:<8} "
              f"{'FAIL: ' + '; '.join(r['problems']) if r['problems'] else 'PASS'}")
    n_fail = sum(1 for r in results if r["problems"])
    print(f"\n{len(results) - n_fail}/{len(results)} PASS")


def test_detector_cases():
    results = run_all()
    assert results, f"no cases in {CASES_DIR}"
    failed = {r["case"]: r["problems"] for r in results if r["problems"]}
    assert not failed, failed


def score_trace(name: str, path: Path, source: str) -> dict:
    """Score a real sandbox trace (no expectations) for the coverage matrix."""
    report = build_behavioral_report(json.loads(path.read_text(encoding="utf-8")))
    risk, level, _ = compute_risk_score(report)
    return {"case": name, "source": source, "risk": risk, "level": level,
            "fired": sorted(d for d in DETECTORS if report["indicators"].get(d)), "problems": None}


def write_matrix(results: list, traces: list, out: Path) -> None:
    rows = [{**r, "source": "synthetic"} for r in results] + traces
    head = "| case | source | " + " | ".join(DETECTORS) + " | risk | level | expect |"
    lines = [
        "# Detector coverage matrix",
        "",
        "Generated by `py tests/detectors/run.py --matrix` (traces: tests/detectors/fixtures/, see its",
        "README; override with --canary / --provenance); scored with",
        "worker/risk.py. Cell: **fire** = indicator true, `-` = not. Sources:",
        "",
        "- **synthetic**: tests/detectors/cases/*.json (expectation checked; PASS/FAIL).",
        "- **canary**: real trace of the sensor smoke test (sandbox/canary, `sandbox/smoke_test.py`).",
        "  Its hosts are `*.invalid`, which risk.py treats as harness hosts, so undeclared /",
        "  beaconing / script_injection are not expected to fire there.",
        "- **provenance**: real trace of eval/provenance_benchmark (attribution test; its own",
        "  TP/FP/FN/TN is printed by score.py). It checks the origin attribution that",
        "  undeclared_domain_contact relies on, not the detectors: the fixture declares every",
        "  host it contacts, so no detector is expected to fire on it.",
        "- `not run` = that trace file was not found.",
        "",
        head,
        "|" + "---|" * (len(DETECTORS) + 5),
    ]
    for r in rows:
        cells = ["**fire**" if d in r["fired"] else "-" for d in DETECTORS]
        exp = "-" if r["problems"] is None else ("FAIL" if r["problems"] else "PASS")
        lines.append(f"| {r['case']} | {r['source']} | " + " | ".join(cells)
                     + f" | {r['risk']} | {r['level']} | {exp} |")

    lines += ["", "## Per detector", "",
              "| detector | synthetic fire | synthetic no-fire | canary | provenance |",
              "|---|---|---|---|---|"]
    for d in DETECTORS:
        pos = [r["case"] for r in results if d in r["fired"]]
        neg = [r["case"] for r in results if d not in r["fired"]]

        def trace_cell(src):
            ts = [t for t in traces if t["source"] == src]
            return ("fire" if any(d in t["fired"] for t in ts) else "no") if ts else "not run"
        lines.append(f"| {d} | {len(pos)}{' (' + ', '.join(pos) + ')' if pos else ''} | {len(neg)} | "
                     f"{trace_cell('canary')} | {trace_cell('provenance')} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--matrix", action="store_true", help=f"also write {MATRIX_MD.name}")
    ap.add_argument("--canary", type=Path, default=CANARY_EVENTS,
                    help="events.json of a canary smoke-test run (default: fixtures/canary_corpus.json)")
    ap.add_argument("--provenance", type=Path, default=PROVENANCE_EVENTS,
                    help="events.json of the provenance benchmark (default: fixtures/provenance_corpus.json)")
    a = ap.parse_args()

    results = run_all()
    print_table(results)
    if a.matrix:
        traces = []
        if a.canary and a.canary.exists():
            traces.append(score_trace("canary_smoke", a.canary, "canary"))
        if a.provenance and a.provenance.exists():
            traces.append(score_trace("provenance_benchmark", a.provenance, "provenance"))
        write_matrix(results, traces, MATRIX_MD)
        print(f"-> {MATRIX_MD}")
    return 1 if any(r["problems"] for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
